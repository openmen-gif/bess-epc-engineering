def illustrative_case(capex_factor=1.0, sell=110, buy=40, efficiency=0.85):
    """Annual constant-output pre-tax, unlevered example; USD and MWh."""
    energy = 400 * 300 * 0.97
    gross = energy * (sell - buy / efficiency)
    opex = 400_000 * 8
    capex = 400_000 * 235 * capex_factor
    cash = gross - opex
    npv = -capex + sum(cash / 1.08**year for year in range(1, 16))
    return dict(energy=energy, gross=gross, opex=opex, capex=capex, cash=cash,
                npv=npv, payback=capex/cash if cash > 0 else None)


